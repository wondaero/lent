const START_B = 104, START_C = 105, TO_C = 99, TO_B = 100, STOP = 106

// 위치 i부터 이어지는 숫자 개수
function digitRun(text, i) {
  let n = 0
  while (i + n < text.length && text.charCodeAt(i + n) >= 48 && text.charCodeAt(i + n) <= 57) n++
  return n
}

// 문자열 → 코드 값 배열(시작·체크·정지 포함)
export function code128Values(text) {
  if (!/^[\x20-\x7e]*$/.test(text)) throw new Error('바코드에 쓸 수 없는 문자가 있습니다.')
  const vals = []
  let i = 0
  let set = digitRun(text, 0) >= 4 && digitRun(text, 0) % 2 === 0 ? 'C' : 'B'
  vals.push(set === 'C' ? START_C : START_B)
  while (i < text.length) {
    const run = digitRun(text, i)
    if (set === 'B' && run >= 4) {
      // 홀수 개면 첫 숫자는 B로 보내고 나머지 짝수 개를 C로
      if (run % 2) { vals.push(text.charCodeAt(i) - 32); i++ }
      vals.push(TO_C); set = 'C'
    } else if (set === 'C' && run < 2) {
      vals.push(TO_B); set = 'B'
    } else if (set === 'C') {
      vals.push(Number(text.slice(i, i + 2))); i += 2
    } else {
      vals.push(text.charCodeAt(i) - 32); i++
    }
  }
  const check = vals.reduce((sum, v, k) => sum + v * (k || 1), 0) % 103
  vals.push(check, STOP)
  return vals
}

// 막대/공백 폭 배열(막대부터 번갈아). 합계 = 전체 모듈 수
export function code128Widths(text) {
  return code128Values(text).flatMap((v) => [...PATTERNS[v]].map(Number))
}
